def get_fmp_symbol(ticker: str) -> str:
    """Return the best FMP symbol to use for analyst estimates.

    Logic:
      1. If ticker is in ADR_MAP, return the US ADR symbol — FMP has
         full US analyst consensus (rev estimate, EPS estimate) for it.
      2. Otherwise strip the exchange suffix for the /stable/earnings
         endpoint (which is US-centric and only matches bare symbols).

    Note: for fetch_fmp_single() which uses /income-statement/{symbol},
    the suffixed form (_yahoo_to_fmp) is more correct for non-US tickers.
    Use this function only for the /stable/earnings consensus path.
    """
    if ticker in ADR_MAP:
        return ADR_MAP[ticker]
    return ticker.split(".")[0].upper()



# ── Universe loader ───────────────────────────────────────────────────────────

def load_universe() -> pd.DataFrame:
    """Load MSCI World + MSCI EM CSVs and return a deduplicated ticker universe.

    Sources loaded (in priority order — lower number wins for duplicates):
      1. MSCI World (~1,300 developed-market stocks)
      2. MSCI EM standard (~830 emerging-market stocks)

    Both CSVs are generated by tools/update_msci_world_classification.py v3+,
    which reads the iShares XLS files directly and resolves exchange suffixes
    from the exact exchange-name column (no regex, no country ETFs).

    Each CSV is skipped gracefully if the file doesn't exist (first-run safe).
    Returns DataFrame with columns: Ticker, Company, Country, Sector.
    """
    _sources = [
        ("world", MSCI_CSV),
        ("em",    MSCI_EM_CSV),
    ]

    frames = []
    for source_key, csv_path in _sources:
        if not csv_path.exists():
            print(f"[universe] {source_key.upper()} CSV not found at {csv_path} — skipped "
                  f"(run update_msci_world_classification.py --universe {source_key} to generate)")
            continue
        try:
            df = pd.read_csv(csv_path, dtype=str)
            df["Ticker"] = df["Ticker"].astype(str).str.strip()
            df = df[df["Ticker"].str.len() > 0]
            df["_source"] = source_key
            df["_priority"] = _SOURCE_PRIORITY.get(source_key, 99)
            frames.append(df)
            print(f"[universe] Loaded {len(df):>5} tickers from {source_key.upper()} CSV")
        except Exception as e:
            print(f"[universe] Error loading {source_key.upper()} CSV: {e}")

    if not frames:
        return pd.DataFrame(columns=["Ticker", "Company", "Country", "Sector"])

    combined = pd.concat(frames, ignore_index=True)

    # Dedup: sort ascending so lowest priority number (= highest priority) wins
    combined = combined.sort_values("_priority", ascending=True)
    combined = combined.drop_duplicates(subset=["Ticker"], keep="first")
    combined = combined.drop(columns=["_source", "_priority"], errors="ignore")

    # Normalize Borsa Istanbul tickers: strip -E suffix (KCHOL-E.IS → KCHOL.IS)
    before_norm = combined["Ticker"].copy()
    combined["Ticker"] = combined["Ticker"].str.replace(r"-E\.IS$", ".IS", regex=True)
    normalized = (combined["Ticker"] != before_norm).sum()
    if normalized:
        print(f"[universe] Normalized {normalized} Turkish .IS tickers (stripped -E suffix)")
    combined = combined.drop_duplicates(subset=["Ticker"], keep="first")

    # Apply runtime ticker overrides (symbol renames, corporate actions)
    combined["Ticker"] = combined["Ticker"].replace(TICKER_OVERRIDES)
    combined = combined.drop_duplicates(subset=["Ticker"], keep="first")

    # Ghost filter — safety net for anything that slipped through CSV build
    before = len(combined)
    combined = combined[~combined["Ticker"].apply(is_ghost_ticker)]
    dropped = before - len(combined)
    if dropped:
        print(f"[universe] Dropped {dropped} ghost/placeholder tickers")

    # Dead-market suffix filter — remove exchanges where yfinance returns 0 usable data.
    # These are defined in DEAD_MARKET_SUFFIXES (KL, PS, AD, DU).
    # Filtering here means gc_engine and scan.py never see these tickers at all —
    # they cannot drift into the "active" count via stale cache entries.
    before = len(combined)
    combined = combined[~combined["Ticker"].apply(
        lambda t: (t.rsplit(".", 1)[-1] if "." in t else "US") in DEAD_MARKET_SUFFIXES
    )]
    dead_sfx_dropped = before - len(combined)
    if dead_sfx_dropped:
        print(f"[universe] Dropped {dead_sfx_dropped} tickers on dead-market exchanges "
              f"({', '.join(sorted(DEAD_MARKET_SUFFIXES))})")

    # Known-dead ticker filter — permanently invalid symbols (sanctioned, no Yahoo support).
    # Defined in KNOWN_DEAD_TICKERS. Filtering here avoids wasting gc_engine API calls.
    before = len(combined)
    combined = combined[~combined["Ticker"].isin(KNOWN_DEAD_TICKERS)]
    known_dead_dropped = before - len(combined)
    if known_dead_dropped:
        print(f"[universe] Dropped {known_dead_dropped} known-dead tickers "
              f"(sanctioned / no Yahoo Finance support)")

    print(f"[universe] Total: {len(combined)} unique tickers "
          f"(after ghost={dropped}, dead_suffix={dead_sfx_dropped}, known_dead={known_dead_dropped})")
    return combined.reset_index(drop=True)
